"""Threat-signature updates via freshclam, with pause / resume / stop.

* Pause  — the freshclam process is frozen (SIGSTOP); nothing is downloaded until it continues.
* Resume — the process continues (SIGCONT). If the server closed the connection during a long
           pause, freshclam fails; the updater then restarts it automatically. Database files that
           were already completed are kept, so only the interrupted file is downloaded again.
* Stop   — freshclam is terminated and its temporary files are removed.
"""
import getpass
import os
import re
import shutil
import signal
import subprocess
import threading
import time

from linux_defender import paths

_PROGRESS = re.compile(r"([\d.]+)\s*([KMG]i?B)\s*/\s*([\d.]+)\s*([KMG]i?B)")
_UNITS = {"KiB": 1 << 10, "MiB": 1 << 20, "GiB": 1 << 30, "KB": 1e3, "MB": 1e6, "GB": 1e9}

IDLE, RUNNING, PAUSED, STOPPING = "idle", "running", "paused", "stopping"
AUTO_RESUME_ATTEMPTS = 3


def _bytes(n, unit):
    return float(n) * _UNITS.get(unit, 1)


class Updater:
    """Runs freshclam with a per-user config; reports progress and state through callbacks."""

    def __init__(self, settings, on_progress=None, on_done=None, on_state=None):
        self.settings = settings
        self.on_progress = on_progress or (lambda text, frac: None)
        self.on_done = on_done or (lambda ok, changed, message: None)
        self.on_state = on_state or (lambda state: None)
        self.proc = None
        self.state = IDLE
        self.cancelled = False
        self.last_cancelled = False
        self.progress_text = ""
        self.progress_frac = -1.0
        self._lock = threading.Lock()
        self._paused_this_attempt = False

    # -- state ---------------------------------------------------------------
    @property
    def running(self) -> bool:
        """True while an update is in progress (also while paused or stopping)."""
        return self.state != IDLE

    def _set_state(self, st):
        self.state = st
        try:
            self.on_state(st)
        except Exception:
            pass

    def _progress(self, text, frac):
        # a line that was already in the pipe when Pause was pressed must not hide the "Paused" state
        if self.state == PAUSED and not text.startswith("Paused"):
            self.progress_text, self.progress_frac = text, (frac if frac >= 0 else self.progress_frac)
            text, frac = self._paused_text(), self.progress_frac
        else:
            self.progress_text, self.progress_frac = text, frac
        self.on_progress(text, frac)

    # -- config --------------------------------------------------------------
    def write_config(self):
        px = self.settings.get("update.proxy")
        lines = [
            "# Generated by Linux Defender — edits are overwritten",
            f"DatabaseDirectory {paths.DB_DIR}",
            f"DatabaseOwner {getpass.getuser()}",
            *paths.certs_config_lines(),
            f"UpdateLogFile {paths.LOG_DIR / 'freshclam.log'}",
            "LogTime yes",
            "LogFileMaxSize 2M",
            "LogRotate yes",
            "DatabaseMirror database.clamav.net",
            "DNSDatabaseInfo current.cvd.clamav.net",
            "ConnectTimeout 30",
            "ReceiveTimeout 0",
            "MaxAttempts 3",
            "ScriptedUpdates yes",
            "Bytecode yes",
            "TestDatabases yes",
            "Foreground yes",
        ]
        if px.get("enabled") and px.get("host"):
            lines += [f"HTTPProxyServer {px['host']}", f"HTTPProxyPort {int(px.get('port') or 8080)}"]
            if px.get("user"):
                lines += [f"HTTPProxyUsername {px['user']}", f"HTTPProxyPassword {px.get('password', '')}"]
        paths.FRESHCLAM_CONF.parent.mkdir(parents=True, exist_ok=True)
        paths.FRESHCLAM_CONF.write_text("\n".join(lines) + "\n", encoding="utf-8")
        paths.FRESHCLAM_CONF.chmod(0o600)

    # -- controls ------------------------------------------------------------
    def start(self):
        with self._lock:
            if self.state != IDLE:
                return False
            self.cancelled = False
            self.last_cancelled = False
            self._set_state(RUNNING)
        threading.Thread(target=self._run, daemon=True, name="freshclam").start()
        return True

    def pause(self):
        with self._lock:
            p = self.proc
            if self.state != RUNNING or not p or p.poll() is not None:
                return False
            try:
                os.kill(p.pid, signal.SIGSTOP)
            except OSError:
                return False
            self._paused_this_attempt = True
            self._set_state(PAUSED)
        self.on_progress(self._paused_text(), self.progress_frac)
        return True

    def resume(self):
        with self._lock:
            p = self.proc
            if self.state != PAUSED:
                return False
            if p and p.poll() is None:
                try:
                    os.kill(p.pid, signal.SIGCONT)
                except OSError:
                    pass
            self._set_state(RUNNING)
        self.on_progress(self.progress_text or "Resuming…", self.progress_frac)
        return True

    def stop(self):
        """Cancel the download entirely (works while running or paused)."""
        with self._lock:
            if self.state in (IDLE, STOPPING):
                return False
            self.cancelled = True
            p = self.proc
            self._set_state(STOPPING)
        self.on_progress("Stopping…", -1)
        if p and p.poll() is None:
            try:
                p.terminate()                      # queued while frozen …
                os.kill(p.pid, signal.SIGCONT)     # … delivered as soon as it continues
            except OSError:
                pass

            def killer():
                try:
                    p.wait(6)
                except subprocess.TimeoutExpired:
                    try:
                        p.kill()
                    except OSError:
                        pass
            threading.Thread(target=killer, daemon=True).start()
        return True

    # kept for callers of the old API
    cancel = stop

    def _paused_text(self):
        base = self.progress_text or "Download"
        for prefix in ("Paused — ",):
            if base.startswith(prefix):
                base = base[len(prefix):]
        return "Paused — " + base

    # -- worker --------------------------------------------------------------
    def _run(self):
        changed = False
        ok = False
        message = ""
        try:
            fc = paths.find_tool("freshclam")
            if not fc:
                message = "freshclam not found"
                return
            self.write_config()
            self.settings.set("update.last_check", time.time())
            attempts = 0
            while True:
                attempts += 1
                self._paused_this_attempt = False
                rc, ch, last_lines = self._run_freshclam(fc, attempts)
                changed = changed or ch
                if self.cancelled:
                    break
                if rc == 0:
                    ok = True
                    break
                # a long pause can make the server drop the connection: continue automatically
                if self._paused_this_attempt and attempts <= AUTO_RESUME_ATTEMPTS:
                    self._progress("The connection was closed during the pause. Continuing the download…", -1)
                    time.sleep(2)
                    if self.cancelled:
                        break
                    continue
                errs = [l for l in last_lines if "error" in l.lower() or "warning" in l.lower()]
                errs = [l for l in errs if "initialization error" not in l.lower()] or errs
                message = (errs[0] if errs else (last_lines[-1] if last_lines else f"freshclam exit code {rc}"))
                message = re.sub(r"(WARNING|ERROR):\s*\w{3} \w{3}\s+\d+ [\d:]+ \d+ ->\s*", "", message).strip()
                break
            if self.cancelled:
                self._cleanup_partial()
                message = "Download stopped. Database files that had finished downloading were kept."
            elif ok:
                self.settings.set("update.last_success", time.time())
                message = "Threat signatures are up to date" if not changed else "Threat signatures updated"
        except Exception as e:  # pragma: no cover - defensive
            message = str(e)
        finally:
            self.last_cancelled = self.cancelled
            self.proc = None
            self.progress_text, self.progress_frac = "", -1.0
            self._set_state(IDLE)
            self.on_done(ok, changed, message)

    def _run_freshclam(self, fc, attempt):
        changed = False
        self._progress("Checking for updates…" if attempt == 1 else "Reconnecting…", -1)
        proc = subprocess.Popen(
            [fc, "--config-file", str(paths.FRESHCLAM_CONF), "--stdout", "--show-progress"],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=paths.tool_env(), bufsize=0,
        )
        with self._lock:
            self.proc = proc
            if self.cancelled:                      # stop() raced with the start
                proc.terminate()
        buf = b""
        last_lines = []
        current = ""
        while True:
            ch = proc.stdout.read(1)
            if not ch:
                break
            if ch in (b"\r", b"\n"):
                line = buf.decode(errors="replace").strip()
                buf = b""
                if not line or self.state in (PAUSED, STOPPING):
                    if line and ch == b"\n":
                        last_lines = (last_lines + [line])[-12:]
                    continue
                m = _PROGRESS.search(line)
                if m:
                    done = _bytes(m.group(1), m.group(2))
                    total = _bytes(m.group(3), m.group(4))
                    frac = done / total if total else -1
                    self._progress(f"{current} {m.group(1)} {m.group(2)} / {m.group(3)} {m.group(4)}".strip(), frac)
                    continue
                if ch == b"\n":
                    last_lines = (last_lines + [line])[-12:]
                low = line.lower()
                if "downloading" in low or "retrieving" in low or "testing database" in low:
                    current = line.split("]")[-1].strip() if "]" in line else line
                    self._progress(current, -1)
                if "updated (version" in low or "database available for update" in low:
                    changed = True
                if "available for update" in low or "available for download" in low:
                    current = f"Downloading {line.split()[0]} database:"
                    self._progress(current, -1)
            else:
                buf += ch
        rc = proc.wait()
        return rc, changed, last_lines

    def _cleanup_partial(self):
        """Remove freshclam's temporary download/test files left behind by a stop."""
        try:
            for p in paths.DB_DIR.iterdir():
                n = p.name
                if p.is_dir() and n.startswith("tmp."):
                    shutil.rmtree(p, ignore_errors=True)
                elif p.is_file() and (n.endswith((".tmp", ".part")) or ".tmp-" in n or n.startswith("tmp.")):
                    p.unlink(missing_ok=True)
        except OSError:
            pass
